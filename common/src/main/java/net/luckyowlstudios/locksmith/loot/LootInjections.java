package net.luckyowlstudios.locksmith.loot;

import net.luckyowlstudios.locksmith.init.ModItems;
import net.minecraft.resources.ResourceKey;
import net.minecraft.world.item.Item;
import net.minecraft.world.level.storage.loot.BuiltInLootTables;
import net.minecraft.world.level.storage.loot.LootTable;

import java.util.List;
import java.util.function.Supplier;

/**
 * Items Locksmith adds to vanilla loot tables. This list is the single source of truth: NeoForge
 * datagen turns each entry into a global loot modifier, and Fabric adds each entry with its loot
 * table event.
 */
public final class LootInjections {

    /** Adds one {@code item} to the loot generated by {@code table}, with the given chance (1 = always). */
    public record Injection(String name, ResourceKey<LootTable> table, Supplier<Item> item, float chance) {
    }

    public static final List<Injection> ALL = List.of(
            // Dungeon slimes are the main source of golden keys. Nether fortress chests sometimes hold
            // one too, so players on Peaceful can still find them.
            new Injection("golden_key_to_nether_fortress_chest",
                    BuiltInLootTables.NETHER_BRIDGE,
                    ModItems.GOLDEN_KEY, 0.15F)
    );

    private LootInjections() {
    }
}
